/**
 * 文章に「金額」が含まれているかの判定（純粋関数・テストから直接読める）。
 *
 * LINEに「お昼ご飯にうどん500円」のように送ると、AIの振り分けでは「食事」と判定されて
 * 食事だけが記録され、支出が登録されないことがあった。金額（円）が書かれている場合は
 * 必ず支出としても登録するために、この判定を使う。
 */

/** 全角数字・記号をそろえる。 */
function normalize(text: string): string {
  return (text ?? "").normalize("NFKC");
}

/**
 * 金額らしい表記が含まれているか。
 * 「500円」「1,200円」「1万円」「1.5万円」「¥980」「500 円」などを拾い、
 * 「60kg」「10回」「300グラム」のような数量表記は拾わない。
 */
export function containsMoneyAmount(text: string): boolean {
  const t = normalize(text);
  // 数字（カンマ・小数点可）＋（万/千）＋円 / 圓
  if (/\d[\d,]*(?:\.\d+)?\s*(?:万|千)?\s*(?:円|圓)/.test(t)) return true;
  // 通貨記号が数字の前に付く表記（¥980, \980, ￥1,200）
  if (/[¥\\]\s*\d[\d,]*(?:\.\d+)?/.test(t)) return true;
  // 「一万円」「五百円」のような漢数字（よく使う範囲だけ）
  if (/[一二三四五六七八九十百千万]+\s*円/.test(t)) return true;
  return false;
}
